def check_generated_ledgers(root: Path) -> tuple[str, ...]:
    """Return deterministic drift errors for both generated ledgers and constants."""

    import pyowl_core

    errors: list[str] = []
    expected_files = {
        root / "schemas" / "encoded-view-v1.json": render_encoded_view_descriptor(),
        root / "schemas" / "encoded-view-v1.toml": render_encoded_view_schema(),
        root / "schemas" / "version-decision-v1.toml": render_version_decision(),
    }
    for path, expected in expected_files.items():
        try:
            observed = path.read_bytes() if isinstance(expected, bytes) else path.read_text(
                encoding="utf-8"
            )
        except OSError:
            errors.append(f"missing generated ledger: {path.relative_to(root)}")
        else:
            if observed != expected:
                errors.append(f"generated ledger is stale: {path.relative_to(root)}")
    runtime = (
        pyowl_core.API_VERSION,
        pyowl_core.ADAPTER_PROTOCOL_VERSION,
        pyowl_core.MODEL_SCHEMA_VERSION,
        pyowl_core.WIRE_FORMAT_VERSION,
        pyowl_core.__version__,
    )
    expected_runtime = ((0, 1), 1, 1, (1, 1), "0.1.0")
    if runtime != expected_runtime:
        errors.append(f"runtime version decision drifted: {runtime!r}")
    return tuple(errors)


def _write_generated_ledgers(root: Path) -> None:
    text_targets = {
        root / "schemas" / "encoded-view-v1.toml": render_encoded_view_schema(),
        root / "schemas" / "version-decision-v1.toml": render_version_decision(),
    }
    for path, content in text_targets.items():
        path.write_text(content, encoding="utf-8", newline="\n")
    (root / "schemas" / "encoded-view-v1.json").write_bytes(
        render_encoded_view_descriptor()
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "generate"))
    arguments = parser.parse_args(argv)
    root = Path(__file__).resolve().parents[2]
    if arguments.command == "generate":
        _write_generated_ledgers(root)
        return 0
    errors = check_generated_ledgers(root)
    for error in errors:
        print(error)
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())


